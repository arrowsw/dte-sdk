/**
 * EN: One row of a customs table: its code, its name and, where the annex gives one, the abbreviation customs asks
 * for in a declaration; a port also carries the heading it is listed under.
 * ES: Una fila de una tabla de Aduanas: su código, su nombre y, donde el anexo la da, la sigla que Aduanas pide en una
 * declaración; un puerto lleva además el encabezado bajo el que está listado.
 */
