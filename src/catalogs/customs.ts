// A name by its letters and digits alone: case, accents, spaces and punctuation do not count.
const key = (text: string): string =>
  text
    .normalize('NFD')
    .toUpperCase()
    .replace(/[^A-Z0-9]/g, '')

/**
 * EN: The code of a name in a customs table, or null. The name is matched whole, by its letters and digits alone
 * (case, accents and punctuation do not count), against the name and the abbreviation of each row; a part of a name
 * matches nothing. When rows of different codes match, the answer is null rather than one of them: give `group`, the
 * heading of the port, to tell them apart (`SAN FRANCISCO` is a port of the United States and a border crossing of
 * Chile).
 * ES: El código de un nombre en una tabla de Aduanas, o null. El nombre se compara entero, solo por sus letras y
 * dígitos (mayúsculas, acentos y puntuación no cuentan), contra el nombre y la sigla de cada fila; una parte de un
 * nombre no calza con nada. Si calzan filas de códigos distintos, la respuesta es null y no una de ellas: entregue
 * `group`, el encabezado del puerto, para distinguirlas (`SAN FRANCISCO` es un puerto de Estados Unidos y un paso
 * fronterizo de Chile).
 * @param table EN: one of the customs tables. ES: una de las tablas de Aduanas.
 * @param name EN: the name or the abbreviation to look for. ES: el nombre o la sigla por buscar.
 * @param group EN: the heading the row is listed under, for a port. ES: el encabezado bajo el que está la fila, para un puerto.
 * @returns EN: the code, or null when no row or rows of several codes match. ES: el código, o null si no calza ninguna fila o calzan filas de varios códigos.
 */
export const customsCode = (table: readonly CustomsEntry[], name: string, group?: string): number | null => {
  const wanted = key(String(name))
  const codes = new Set(
    table
      .filter((entry) => group === undefined || key(entry.group ?? '') === key(String(group)))
      .filter((entry) => wanted !== '' && [entry.name, entry.abbreviation ?? ''].some((text) => key(text) === wanted))
      .map((entry) => entry.code),
  )
  return codes.size === 1 ? [...codes][0] : null
}

/**
 * EN: The name a customs table gives a code, or null when it lists none. Where the annex lists a code twice, the
 * first row is the answer.
 * ES: El nombre que una tabla de Aduanas da a un código, o null si no lo lista. Donde el anexo lista un código dos
 * veces, responde la primera fila.
 * @param table EN: one of the customs tables. ES: una de las tablas de Aduanas.
 * @param code EN: the code. ES: el código.
 * @returns EN: the name, or null. ES: el nombre, o null.
 */
export const customsName = (table: readonly CustomsEntry[], code: number): string | null =>
  table.find((entry) => entry.code === Number(code))?.name ?? null
