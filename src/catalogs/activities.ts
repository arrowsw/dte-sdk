export const businessActivity = (code: number): BusinessActivity | undefined => BY_CODE.get(code)

/**
 * EN: Type guard: true when `value` is a code of `BUSINESS_ACTIVITIES`.
 * ES: Guarda de tipo: true cuando `value` es un código de `BUSINESS_ACTIVITIES`.
 */
export const isBusinessActivityCode = (value: unknown): value is number =>
  typeof value === 'number' && BY_CODE.has(value)
