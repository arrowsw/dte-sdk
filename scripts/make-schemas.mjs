// Writes `src/schemas/sources.ts` from the SII's schema files in `tests/fixtures/xsd`, so the package carries them as
// text and needs no file system to validate. The files are ISO-8859-1: each is decoded, its line ends are made `\n`,
// and its declaration is made to say UTF-8, which is what the text is once it is a string. Run with `npm run schemas`
// after a schema changes; `tests/schemas/schemas.test.ts` fails when the two drift apart.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const SOURCE_DIR = 'tests/fixtures/xsd'
const TARGET = 'src/schemas/sources.ts'

export const schemaText = (bytes) =>
  bytes.toString('latin1').replace(/\r\n?/g, '\n').replace('encoding="ISO-8859-1"', 'encoding="UTF-8"')

const literal = (text) => `\`${text.replace(/\\/g, '\\\\').replace(/`/g, '\\`').replace(/\$\{/g, '\\${')}\``

const files = readdirSync(SOURCE_DIR)
  .filter((name) => name.endsWith('.xsd'))
  .sort()

const entries = files.map((name) => `  '${name}': ${literal(schemaText(readFileSync(join(SOURCE_DIR, name))))},`)

writeFileSync(
  TARGET,
  `// Generated by scripts/make-schemas.mjs from the SII's schema files. Do not edit: run \`npm run schemas\`.

/**
 * EN: The SII's schema files as text, by file name, as the SII publishes them except for their charset: decoded from
 * ISO-8859-1, with \`\\n\` line ends and a declaration that says UTF-8.
 * ES: Los archivos de esquema del SII como texto, por nombre de archivo, tal como los publica el SII salvo por su
 * charset: decodificados desde ISO-8859-1, con fines de línea \`\\n\` y una declaración que dice UTF-8.
 */
export const SCHEMA_SOURCES = {
${entries.join('\n')}
} as const
`,
)
console.log(`${TARGET}: ${files.length} schemas`)
